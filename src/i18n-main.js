// Languages for the main process: its dialogs, the errors it hands the window,
// export headers and the prompts it sends Claude. Same style as the window's
// i18n.js: the Portuguese string is the key, t(pt, { slot }) fills {slot}, and
// a missing translation falls back to the Portuguese. The language comes from
// a getter main.js sets with usaIdioma (config.idioma, or the system locale).

let obter = () => "pt";
export function usaIdioma(fn) { obter = fn; }
export const idioma = () => { const l = obter(); return l === "en" || l === "tr" ? l : "pt"; };
export const nomeIdioma = () => ({ pt: "Brazilian Portuguese", en: "English", tr: "Turkish" })[idioma()];
// the system locale to a language of ours: tr* → tr, pt* → pt, anything else → en
export const detectaIdioma = (locale) => { const l = String(locale || "").toLowerCase(); return l.startsWith("tr") ? "tr" : l.startsWith("pt") ? "pt" : "en"; };

const preenche = (s, v) => (v ? s.replace(/\{(\w+)\}/g, (m, k) => (k in v ? v[k] : m)) : s);
export function t(pt, vars) { const l = idioma(); return preenche(l === "pt" ? pt : DIC[l][pt] ?? pt, vars); }

